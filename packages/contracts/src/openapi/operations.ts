export type ComponentName = keyof typeof componentSchemas;

export type Method = 'get' | 'post' | 'put' | 'patch' | 'delete';

export interface Operation {
  method: Method;
  /** OpenAPI path template, e.g. `/v1/missions/{id}`. */
  path: string;
  operationId: string;
  tag: string;
  summary: string;
  description?: string;
  /** `public` needs no credential; `operator` is the static operator token; `user` is a JWT. */
  auth: 'public' | 'user' | 'operator';
  query?: z.ZodObject;
  body?: ComponentName;
  /** The mission version last seen, required on every mission change (DESIGN.md §13). */
  ifMatch?: boolean;
  success: { status: 200 | 201 | 204; schema?: ComponentName; description: string; etag?: boolean };
  /** Statuses beyond those every operation of this shape has (401, 400, 413, 415, 500). */
  errors?: readonly number[];
}

